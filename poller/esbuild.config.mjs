// Builds poller/dist: a self-contained Functions app that `func start` runs from this directory
// and infra/deploy.sh zips as is (plan decision 30; Kudu cannot resolve pnpm workspace links).
//
//   dist/index.js                        one esbuild bundle: the entry registers both functions, so
//                                        they share a single copy of @frejsi/shared (telemetry,
//                                        Prisma client); package.json#main's glob matches it
//   dist/host.json                       copied
//   dist/package.json                    the externals below as its only dependencies
//   dist/node_modules/                   those externals, flat, plus the generated Prisma client
//                                        with its query engine for the Function App's Linux
//
// Run with `pnpm --filter ./poller build`. `src/index.test.ts` reads the two lists below.
import { execFileSync } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const here = path.dirname(fileURLToPath(import.meta.url));
const dist = path.join(here, "dist");
const require = createRequire(path.join(here, "package.json"));

/**
 * Left out of the bundle. Prisma's client loads its engine by path, the telemetry SDK hooks
 * `require` at runtime, and `@azure/functions-core` is the host's own module.
 */
export const EXTERNALS = [
  "@prisma/client",
  ".prisma/client",
  "@azure/functions-core",
  "applicationinsights",
  "@opentelemetry/api-logs",
];

/** Provided by the Functions host or generated by Prisma: never a dependency of this package. */
export const PROVIDED_AT_RUNTIME = ["@azure/functions-core", ".prisma/client"];

export const ENTRY_POINTS = ["src/index.ts"];

function readPackage() {
  return JSON.parse(readFileSync(path.join(here, "package.json"), "utf8"));
}

/** The dependencies dist/package.json declares: every external that is a real package, pinned. */
export function distDependencies(pkg = readPackage()) {
  const dependencies = {};
  for (const name of EXTERNALS) {
    if (PROVIDED_AT_RUNTIME.includes(name)) continue;
    const version = pkg.dependencies?.[name];
    if (!version)
      throw new Error(`${name} is external but not a dependency of poller/package.json`);
    dependencies[name] = version;
  }
  return dependencies;
}

async function bundle() {
  await build({
    entryPoints: ENTRY_POINTS.map((p) => path.join(here, p)),
    outdir: dist,
    outbase: path.join(here, "src"),
    bundle: true,
    platform: "node",
    target: "node22",
    format: "cjs",
    external: EXTERNALS,
    logLevel: "warning",
  });
}

function writeDistPackage(pkg) {
  writeFileSync(
    path.join(dist, "package.json"),
    JSON.stringify(
      {
        name: pkg.name,
        version: pkg.version,
        private: true,
        description: pkg.description,
        license: pkg.license,
        main: "{index,functions/*}.js",
        dependencies: distDependencies(pkg),
      },
      null,
      2,
    ) + "\n",
  );
}

/** pnpm, the one running this script when it is `pnpm build`, otherwise the one on PATH. */
function pnpm(args) {
  const execPath = process.env.npm_execpath;
  const [cmd, argv] =
    execPath && /pnpm/.test(execPath) ? [process.execPath, [execPath, ...args]] : ["pnpm", args];
  execFileSync(cmd, argv, { cwd: dist, stdio: ["ignore", "ignore", "inherit"] });
}

/** A flat node_modules of the externals, from the store when it has them. No scripts run. */
function installExternals() {
  pnpm([
    "install",
    "--ignore-workspace",
    "--prod",
    "--ignore-scripts",
    "--prefer-offline",
    "--config.node-linker=hoisted",
    "--config.confirm-modules-purge=false",
  ]);
  rmSync(path.join(dist, "pnpm-lock.yaml"), { force: true });
}

/** The client `prisma generate` wrote for shared/prisma/schema.prisma, engine included. */
function copyGeneratedPrismaClient() {
  const clientPackage = realpathSync(require.resolve("@prisma/client/package.json"));
  const generated = path.join(
    path.dirname(path.dirname(path.dirname(clientPackage))),
    ".prisma",
    "client",
  );
  if (!existsSync(path.join(generated, "schema.prisma"))) {
    throw new Error(
      `no generated Prisma client at ${generated}; run pnpm install (prisma generate)`,
    );
  }
  const target = path.join(dist, "node_modules", ".prisma", "client");
  mkdirSync(path.dirname(target), { recursive: true });
  cpSync(generated, target, { recursive: true, dereference: true });
}

/** Proves dist stands alone: every external and the bundles load from dist with no NODE_PATH. */
function smoke() {
  const script = [
    ...EXTERNALS.filter((n) => !PROVIDED_AT_RUNTIME.includes(n)).map(
      (n) => `require(${JSON.stringify(n)});`,
    ),
    'require("./node_modules/.prisma/client/package.json");',
    'const client = require("@prisma/client"); if (typeof client.PrismaClient !== "function") throw new Error("PrismaClient missing");',
    'require("./index.js");',
  ].join("\n");
  execFileSync(process.execPath, ["--input-type=commonjs", "-e", script], {
    cwd: dist,
    env: { ...process.env, NODE_PATH: "" },
    stdio: ["ignore", "ignore", "inherit"],
  });
}

async function main() {
  const pkg = readPackage();
  rmSync(dist, { recursive: true, force: true });
  mkdirSync(dist, { recursive: true });
  await bundle();
  cpSync(path.join(here, "host.json"), path.join(dist, "host.json"));
  writeDistPackage(pkg);
  installExternals();
  copyGeneratedPrismaClient();
  smoke();
  process.stdout.write("poller/dist is ready: bundles, host.json, package.json, node_modules\n");
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
