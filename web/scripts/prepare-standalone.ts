// Turn Next's standalone output into the bundle Static Web Apps deploys, and that the isolated
// release e2e runs as is (scripts/release-server.ts).
//
// 1. Next's trace misses the generated Prisma engine in pnpm's virtual store. Include the client
//    beside its traced package at the same relative path.
// 2. Static Web Apps runs the bundle as a self-contained app: it starts `node server.js` at the
//    bundle's root, and its upload writes the warm-up probe file `/.swa/health.html` ("healthy")
//    into the root public/, where a flat Next app serves from. The monorepo trace nests the app
//    under web/, so the assets go in there, and a generated CommonJS root `server.js` copies the
//    probe file into web/public/, listens on every interface (App Service sets HOSTNAME to the
//    container's name, and Next binds to it) and starts web/server.js. The build ships its own
//    copy of the probe file for runs outside Static Web Apps. Each of these, missing, ends the
//    deploy in "Web app warm up timed out" (v0.2.1 to v0.3.0; found with diagnostics in the app).
// 3. No symlinks. The GitHub artifact between release jobs drops them, and a copied pnpm link
//    cannot find its package's dependencies; .npmrc installs a flat node_modules, and the build
//    fails if a link reaches the bundle again (the v0.2.2 deploy timed out warming up on this).
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const root = path.resolve(process.cwd(), "..");
const standalone = path.join(root, "web/.next/standalone");
const requireShared = createRequire(path.join(root, "shared/package.json"));
const generated = path.resolve(
  path.dirname(requireShared.resolve("@prisma/client/package.json")),
  "../../.prisma/client",
);
if (!existsSync(generated)) throw new Error("Run pnpm install to generate the Prisma client first");
cpSync(generated, path.join(standalone, path.relative(root, generated)), { recursive: true });

const app = path.join(standalone, "web");
if (!existsSync(path.join(app, "server.js"))) {
  throw new Error(`No server.js in ${app}: the standalone layout changed; update this script`);
}
cpSync(path.join(root, "web/.next/static"), path.join(app, ".next/static"), { recursive: true });
cpSync(path.join(root, "web/public"), path.join(app, "public"), { recursive: true });
// The probe file exactly as the upload writes it: seven bytes, no newline.
mkdirSync(path.join(app, "public/.swa"), { recursive: true });
writeFileSync(path.join(app, "public/.swa/health.html"), "healthy");

// The trace copies either the workspace's package.json ("type": "module") or web's to the bundle's
// root, depending on the machine. The generated server.js is CommonJS like web/server.js, so the
// root package.json is written here, the same everywhere.
const rootPackage = JSON.parse(readFileSync(path.join(standalone, "package.json"), "utf8")) as {
  license?: string;
};
writeFileSync(
  path.join(standalone, "package.json"),
  JSON.stringify(
    {
      name: "frejsi-web-bundle",
      private: true,
      license: rootPackage.license ?? "AGPL-3.0-only",
      type: "commonjs",
      scripts: { start: "node server.js" },
    },
    null,
    2,
  ) + "\n",
);
writeFileSync(
  path.join(standalone, "server.js"),
  [
    "// Generated by web/scripts/prepare-standalone.ts. Static Web Apps starts the bundle with",
    "// `node server.js` at its root; the monorepo trace put the Next.js server in web/.",
    'const fs = require("node:fs");',
    'const path = require("node:path");',
    "",
    "// The upload writes its warm-up probe file (/.swa/health.html) into the root public/, where a",
    "// flat Next app serves from; this server serves web/public/.",
    "try {",
    '  fs.cpSync(path.join(__dirname, "public", ".swa"), path.join(__dirname, "web", "public", ".swa"), {',
    "    recursive: true,",
    "  });",
    "} catch {",
    "  // Not deployed by Static Web Apps (local runs, the release e2e): the build's copy serves.",
    "}",
    "",
    "// Next listens on $HOSTNAME, which App Service sets to the container's name.",
    'process.env.HOSTNAME = "0.0.0.0";',
    "",
    'require("./web/server.js");',
    "",
  ].join("\n"),
);

const links = readdirSync(standalone, { recursive: true, withFileTypes: true }).filter((entry) =>
  entry.isSymbolicLink(),
);
const [firstLink] = links;
if (firstLink) {
  const first = path.relative(standalone, path.join(firstLink.parentPath, firstLink.name));
  throw new Error(
    `The standalone bundle contains ${String(links.length)} symlink(s), first ${first}; the release ` +
      "artifact drops them. Is node-linker=hoisted still in .npmrc? Run pnpm install again.",
  );
}
